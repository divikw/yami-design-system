export function componentForTitle(title: string) {
  if (!/^YAMI\/(components|modules|assets\/membership)\//i.test(title)) return undefined;
  return title.split("/").map(segment => names.get(normalize(segment))).reverse().find(Boolean);
}

export function getArgDescription(title: string, name: string, locale: unknown, translations?: DescriptionTranslations) {
  const language = locale === "en" ? "en" : "zh";
  const authored = translations?.[language]?.argDescriptions?.[name];
  if (authored) return authored;
  const component = componentForTitle(title);
  if (!component) return undefined;
  const prop = name.split(".").at(-1)!;
  return (overrides[component]?.[prop] ?? common[prop])?.[language === "zh" ? 0 : 1];
}

export function localizeArgTypes<T extends { description?: string }>(title: string, argTypes: Record<string, T>, locale: unknown, translations?: DescriptionTranslations): Record<string, T> {
  return Object.fromEntries(Object.entries(argTypes).map(([name, argType]) => [name, {
    ...argType, description: getArgDescription(title, name, locale, translations) ?? argType.description,
  }]));
}
